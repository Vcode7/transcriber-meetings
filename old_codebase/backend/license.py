"""
Cryptographic License Verification for VoiceSum Application.

Verifies Ed25519 digitally signed offline licenses (license.key).
Enforces expiration date, integrity signature verification, optional machine binding,
and offline system-clock rollback protection.
"""
import base64
from datetime import date, datetime, timezone
import hashlib
import json
import logging
import os
from pathlib import Path
import platform
import subprocess
import uuid

from cryptography.hazmat.primitives.asymmetric import ed25519
from cryptography.hazmat.primitives import serialization

logger = logging.getLogger("voicesum.license")

# ── EMBEDDED ED25519 PUBLIC VERIFICATION KEY ─────────────────────
# Generated by admin_license/generate_keys.py.
# The private signing key resides exclusively on the administrator machine.
EMBEDDED_PUBLIC_KEY_PEM: bytes = b"""-----BEGIN PUBLIC KEY-----
MCowBQYDK2VwAyEAx0dsm0yZBgw6TayNSUQA3B8tBFHktI5fafPXPmB+5Vk=
-----END PUBLIC KEY-----
"""

BASE_DIR = Path(__file__).resolve().parent
STATE_FILE_PATH = BASE_DIR / ".license_state"

# Default fallback values for backward compatibility
DEFAULT_EXPIRY_DATE: date = date(2026, 10, 15)
LICENSE_EXPIRY_DATE: date = DEFAULT_EXPIRY_DATE


def _get_public_key() -> ed25519.Ed25519PublicKey:
    """Load public key from backend/public_key.pem if available, otherwise embedded constant."""
    pub_file = BASE_DIR / "public_key.pem"
    if pub_file.exists():
        try:
            with open(pub_file, "rb") as f:
                return serialization.load_pem_public_key(f.read())
        except Exception as e:
            logger.warning(f"[License] Could not load {pub_file}: {e}, falling back to embedded key.")
    return serialization.load_pem_public_key(EMBEDDED_PUBLIC_KEY_PEM)


def _canonical_bytes(payload: dict) -> bytes:
    """Deterministic UTF-8 bytes for JSON signature verification."""
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")


def get_current_machine_id() -> str:
    """
    Generate stable SHA-256 machine identifier for hardware binding.
    Does not require internet.
    """
    parts = [
        platform.system(),
        platform.machine(),
        str(uuid.getnode()),
    ]
    if platform.system() == "Windows":
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SOFTWARE\Microsoft\Cryptography") as key:
                guid, _ = winreg.QueryValueEx(key, "MachineGuid")
                if guid:
                    parts.append(str(guid).strip())
        except Exception:
            pass
        try:
            out = subprocess.check_output(
                ["powershell", "-NoProfile", "-NonInteractive", "-Command",
                 "(Get-CimInstance -Class Win32_ComputerSystemProduct).UUID"],
                stderr=subprocess.DEVNULL,
                text=True,
                timeout=5
            ).strip()
            if out and "error" not in out.lower():
                parts.append(out)
        except Exception:
            pass
    elif platform.system() == "Linux":
        for p in ["/etc/machine-id", "/var/lib/dbus/machine-id"]:
            try:
                with open(p, "r", encoding="utf-8") as f:
                    parts.append(f.read().strip())
                    break
            except Exception:
                pass

    raw = "::".join(parts)
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    return f"{digest[:8]}-{digest[8:12]}-{digest[12:16]}-{digest[16:20]}-{digest[20:32]}".upper()


def find_license_path() -> Path | None:
    """Locate license.key in standard locations."""
    env_path = os.environ.get("LICENSE_KEY_PATH")
    if env_path:
        p = Path(env_path)
        if p.exists():
            return p

    candidates = [
        Path.cwd() / "license.key",
        BASE_DIR / "license.key",
        BASE_DIR.parent / "license.key",
    ]
    for c in candidates:
        if c.exists():
            return c
    return None


def _check_clock_tampering(issued_date_str: str) -> tuple[bool, str]:
    """
    Protect against offline system clock rollback.
    1. Checks if current system time is earlier than license issued_date.
    2. Checks if current system time is earlier than the latest recorded run timestamp.
    """
    today = date.today()
    try:
        issued = datetime.strptime(issued_date_str, "%Y-%m-%d").date()
        if today < issued:
            return False, f"System clock error: Current date ({today.isoformat()}) is earlier than license issued date ({issued.isoformat()})."
    except Exception:
        pass

    now_ts = int(datetime.now(timezone.utc).timestamp())
    last_seen_ts = 0

    if STATE_FILE_PATH.exists():
        try:
            with open(STATE_FILE_PATH, "r", encoding="utf-8") as f:
                content = f.read().strip()
                if content:
                    last_seen_ts = int(content)
        except Exception:
            last_seen_ts = 0

    # Allow up to 2 hours of clock skew/timezone drift
    if last_seen_ts > 0 and now_ts < (last_seen_ts - 7200):
        last_seen_date = datetime.fromtimestamp(last_seen_ts, tz=timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        return False, (
            f"System clock rollback detected: Current system clock is earlier than previous application execution "
            f"(Last recorded run: {last_seen_date}). Please restore the correct system time."
        )

    # Update state file with current timestamp
    try:
        with open(STATE_FILE_PATH, "w", encoding="utf-8") as f:
            f.write(str(max(now_ts, last_seen_ts)))
    except Exception:
        pass

    return True, ""


# Cached verification result: (valid, message, payload, check_timestamp)
_LICENSE_CACHE: dict = {}


def check_license(force_reload: bool = False) -> tuple[bool, str]:
    """
    Check whether the application license is still valid.

    Returns
    -------
    (True, "")          — license is valid and verified
    (False, message)    — license verification failed or expired; message contains reason
    """
    global LICENSE_EXPIRY_DATE

    lic_path = find_license_path()
    if not lic_path:
        return (
            False,
            "License file 'license.key' not found. Please place a valid signed license.key in the application directory."
        )

    try:
        with open(lic_path, "r", encoding="utf-8") as f:
            doc = json.load(f)
    except Exception as e:
        return False, f"Failed to read license file '{lic_path.name}': {e}"

    payload = doc.get("payload")
    sig_b64 = doc.get("signature")

    if not isinstance(payload, dict) or not sig_b64:
        return False, "License structure invalid: Missing payload or signature."

    # 1. Verify Cryptographic Signature
    try:
        public_key = _get_public_key()
        sig_bytes = base64.b64decode(sig_b64)
        data = _canonical_bytes(payload)
        public_key.verify(sig_bytes, data)
    except Exception as e:
        return False, f"Signature verification failed: The license file has been modified or corrupted ({e})."

    # 2. Verify Expiration Date
    exp_str = payload.get("expiry_date")
    if not exp_str:
        return False, "License verification failed: Missing expiry_date."

    try:
        exp_date = datetime.strptime(exp_str, "%Y-%m-%d").date()
        LICENSE_EXPIRY_DATE = exp_date
    except Exception as e:
        return False, f"License verification failed: Invalid expiry_date format ({e})."

    today = date.today()
    if today > exp_date:
        days_expired = (today - exp_date).days
        return (
            False,
            f"Demo license expired.\n\n"
            f"License expiry date: {exp_date.isoformat()}.\n\n"
            f"Please contact the administrator for a new license."
        )

    # 3. Check Clock Tampering / Rollback
    issued_str = payload.get("issued_date", "")
    clock_ok, clock_msg = _check_clock_tampering(issued_str)
    if not clock_ok:
        return False, clock_msg

    # 4. Check Machine Binding (if enabled in license)
    signed_machine_id = payload.get("machine_id")
    if signed_machine_id and signed_machine_id.strip().upper() not in ("", "ANY", "NONE"):
        current_id = get_current_machine_id()
        if signed_machine_id.strip().upper() != current_id.strip().upper():
            return (
                False,
                f"Machine/license mismatch: License is bound to machine '{signed_machine_id}', "
                f"but current host ID is '{current_id}'. Application blocked."
            )

    _LICENSE_CACHE["payload"] = payload
    return True, ""


def get_license_info() -> dict:
    """Return dictionary of license payload fields."""
    if "payload" in _LICENSE_CACHE:
        return _LICENSE_CACHE["payload"]

    lic_path = find_license_path()
    if lic_path:
        try:
            with open(lic_path, "r", encoding="utf-8") as f:
                doc = json.load(f)
                return doc.get("payload", {})
        except Exception:
            pass
    return {
        "expiry_date": LICENSE_EXPIRY_DATE.isoformat(),
        "license_type": "demo",
        "customer": "Unknown",
    }


def get_license_expired_body(message: str | None = None) -> dict:
    """Generate HTTP 503 response body for blocked requests."""
    info = get_license_info()
    exp_str = info.get("expiry_date", LICENSE_EXPIRY_DATE.isoformat())
    msg = message or (
        f"Demo license expired.\n\n"
        f"License expiry date: {exp_str}.\n\n"
        f"Please contact the administrator for a new license."
    )
    return {
        "error": "license_expired",
        "expired_on": exp_str,
        "message": msg,
    }


# Backward-compatible dictionary for imports
LICENSE_EXPIRED_BODY: dict = get_license_expired_body()
